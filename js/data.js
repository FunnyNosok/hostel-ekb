/* ---------- Загрузка из localStorage (если админка сохраняла данные) ---------- */

function _loadFromStorage(key, defaults) {
  try {
    const raw = localStorage.getItem(key);
    return raw ? JSON.parse(raw) : defaults;
  } catch {
    return defaults;
  }
}

/* Фото до перехода на папки по адресам — таких файлов в репозитории больше нет. */
const _LEGACY_PHOTO = /^assets\/img\/photo_\d+_/;

/**
 * Админка хранит только id, name, address, price, description, features, photos
 * и держит цену числом. Достраиваем недостающее из дефолтов по id, иначе лендинг
 * останется без street / type / area / specs и упадёт на отрисовке.
 */
function _mergeWithDefaults(stored, defaults) {
  if (!Array.isArray(stored)) return defaults;
  return stored.map((h) => {
    const base = defaults.find((d) => d.id === h.id) || {};
    const photos = (h.photos || []).filter((src) => !_LEGACY_PHOTO.test(src));
    return {
      ...base,
      ...h,
      photos: photos.length ? photos : base.photos || [],
      price: _normalizePrice(h.price, base.price),
    };
  });
}

/* Число из админки → объект, который понимает app.js. 0 означает «цена по запросу». */
function _normalizePrice(price, fallback) {
  if (price && typeof price === 'object') return price;
  if (typeof price !== 'number' || price <= 0) return fallback || { ask: true };
  const base = fallback && !fallback.ask ? fallback : { unit: 'сутки', per: 'за одно место' };
  return { ...base, value: price };
}

